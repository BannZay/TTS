# Packages the CMU Arctic (slt) clips made by experiments\arctic\scripts\build2.py (folder out2) into the voice addon:
#   TTS_Arctic    normal-length clips (names ending 2 = best candidate, 4 = second candidate) + registration
#   (short and long versions, names ending 1 and 3, are no longer packaged; the longer units come from build_arctic_units.py)
# Diphones the corpus still lacks get an alias to the most similar diphone that exists (same voice).
param([string]$OutName='out2', [string]$DestRoot='', [int]$Threads=4, [int]$Quality=5)
$ErrorActionPreference='Stop'
$root = Split-Path $PSScriptRoot -Parent
$src  = Join-Path $root "experiments\arctic\$OutName"
$base = if($DestRoot){ Join-Path $DestRoot 'TTS_Arctic' } else { Join-Path $root 'TTS_Arctic' }
New-Item -ItemType Directory -Force "$base\diphones" | Out-Null; Get-ChildItem "$base\diphones" -Filter *.ogg | Remove-Item

# --- encode all wavs to ogg (parallel ffmpeg) into a temp folder, then move into the addon
$tmp = Join-Path $env:TEMP 'vc_arctic_ogg'; Remove-Item $tmp -Recurse -Force -ea 0; New-Item -ItemType Directory -Force $tmp | Out-Null
Add-Type -TypeDefinition @"
using System.Diagnostics; using System.IO; using System.Threading.Tasks;
public static class ArcticEnc {
  public static void Run(string[] wavs, string outDir, int threads, string q) {
    Parallel.ForEach(wavs, new ParallelOptions { MaxDegreeOfParallelism = threads }, wav => {
      var psi = new ProcessStartInfo("ffmpeg", "-y -loglevel error -i \"" + wav + "\" -ac 1 -c:a libvorbis -q:a " + q + " \"" + Path.Combine(outDir, Path.GetFileNameWithoutExtension(wav) + ".ogg") + "\"");
      psi.UseShellExecute = false; psi.CreateNoWindow = true;
      using (var p = Process.Start(psi)) p.WaitForExit();
    });
  }
}
"@
[ArcticEnc]::Run([string[]]@(Get-ChildItem "$src\wav" -Filter *.wav | % { $_.FullName }), $tmp, $Threads, "$Quality")

# --- table: name -> { seconds, head spectrum, tail spectrum }
$entries = [ordered]@{}
foreach($l in Get-Content "$src\Diphones.lua"){ if($l -match '^\["(\d{5})"\]=(\{.*\}),$'){ $entries[$matches[1]] = $matches[2] } }
$baseLines=@(); $have=@{}
foreach($k in ($entries.PSBase.Keys | Sort-Object)){
  $isBase = $k.EndsWith('2') -or $k.EndsWith('4')
  if(-not $isBase){ continue }   # short/long (1, 3) clips are no longer packaged: the voice has longer units instead (tools/build_arctic_units.py)
  $target = "$base\diphones"
  $ogg = Join-Path $tmp "$k.ogg"
  if(-not (Test-Path $ogg)){ throw "missing encoded clip $k" }
  Move-Item $ogg (Join-Path $target "$k.ogg") -Force
  $line = '["{0}"]={1}' -f $k,$entries[$k]
  if($isBase){ $baseLines += $line; $have[$k.Substring(0,4)] = 1 } }

# --- aliases for what is still missing (keys without a normal clip)
$names = 'AA AE AH0 AH AO AW AY B CH D DH EH ER EY F G HH IH IY JH K L M N NG OW OY P R S SH T TH UH UW V W Y Z ZH'.Split(' ')
$idx=@{}; for($i=0;$i -lt $names.Count;$i++){ $idx[$names[$i]] = $i+1 }
$similar = @{ AA='AO AH'; AE='EH AH'; AH0='AH IH'; AH='AH0 AA'; AO='AA OW'; AW='AY AA'; AY='AW EY'; EH='AE IH'; ER='AH0 AH'; EY='IH IY';
  IH='IY EH'; IY='IH'; OW='AO UH'; OY='AY AO'; UH='UW OW'; UW='UH'; B='P D'; CH='JH SH'; D='T B'; DH='TH D'; F='V TH'; G='K D'; HH='F';
  JH='CH ZH'; K='G T'; L='R W'; M='N B'; N='M NG'; NG='N M'; P='B T'; R='L W'; S='Z SH'; SH='ZH S'; T='D K'; TH='DH F'; V='F B';
  W='Y R'; Y='W IY'; Z='S ZH'; ZH='SH Z' }
function Subs($i){ if($i -eq 0){ return @() }; @($similar[$names[$i-1]].Split(' ') | % { $idx[$_] }) }
$alias=[ordered]@{}; $unfixed=0
foreach($a in 0..40){ foreach($b in 0..40){
  if($a -eq 0 -and $b -eq 0){ continue }
  $key = '{0:00}{1:00}' -f $a,$b
  if($have.ContainsKey($key)){ continue }
  if($a -eq 0 -and 8,9,10,21,28,32 -contains $b){ continue }   # silent stop onsets (kal skips them too)
  $c = @(); foreach($x in (Subs $a)){ $c += ('{0:00}{1:00}' -f $x,$b) }; foreach($y in (Subs $b)){ $c += ('{0:00}{1:00}' -f $a,$y) }
  foreach($x in (Subs $a)){ foreach($y in (Subs $b)){ $c += ('{0:00}{1:00}' -f $x,$y) } }
  $hit = $c | ? { $have.ContainsKey($_) } | select -First 1
  if($hit){ $alias[$key] = $hit } else { $unfixed++ } } }
$al = $alias.PSBase.Keys | % { '["{0}"]="{1}"' -f $_,$alias[$_] }

Set-Content "$base\Diphones.lua" ("-- Generated by tools/build_arctic_addon.ps1 from CMU Arctic slt (see experiments/arctic/scripts/build2.py).`n-- clip name = diphone key (two 2-digit phoneme indices) + 2 (best candidate) or 4 (second candidate) -> { seconds, head spectrum, tail spectrum }`nTTS_ArcticClips = {`n" + ($baseLines -join ",`n") + "`n}`n-- diphones the corpus lacks -> the most similar one that exists`nTTS_ArcticAlias = {`n" + ($al -join ",`n") + "`n}`nTTS_Diphone.RegisterVoice(`"arctic`", { name = `"Arctic`", gender = `"female`", quality = `"natural`", clips = TTS_ArcticClips, alias = TTS_ArcticAlias, base = `"Interface\\AddOns\\TTS_Arctic\\`" })`n") -Encoding ascii
$c = @"
TTS Arctic voice: credits and licence
===========================================

The clips in diphones/ are cut from the CMU ARCTIC speech database, voice "slt" (American English female),
Carnegie Mellon University. The clips are modifications of the original recordings: cut at phoneme boundaries found
by automatic alignment, pitch-flattened and lengthened/shortened with PSOLA (Praat), faded, level-normalised and
re-encoded to Ogg Vorbis.

Licence text of the database (cmu_us_slt_arctic):

"@
$c += (Get-Content (Join-Path $root 'experiments\arctic\COPYING_slt.txt') -Raw)
Set-Content "$base\CREDITS.txt" $c -Encoding ascii
"Arctic: {0} clips {1:N1} MB   aliases {2}, no substitute {3}" -f (gci "$base\diphones" -Filter *.ogg | measure).Count,((gci "$base\diphones" | measure Length -Sum).Sum/1MB),$alias.Count,$unfixed
