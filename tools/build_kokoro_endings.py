"""Builds TTS_KokoroHQ_Endings: the phrase-final ending clips (<key>00f, 00fb, 00fc) of the Kokoro voice.

The clips were cut by tools/build_kokoro.py (WITH_FINAL) from words said alone, so they run about 35% longer than the same
ending cut mid-phrase. This tool speeds each stored clip up by TEMPO with ffmpeg atempo (pitch is kept, so the falling
ending stays) and writes Units.lua with the new lengths (old length / TEMPO; the length of the .ogg file itself is a little padded).

Input:  experiments/kokoro_final_units/Units.lua.bak and units/*.ogg  (the stored clips; never modified)
Output: TTS_KokoroHQ_Endings/Units.lua and units/*.ogg   (or --out DIR)
Usage:  python tools/build_kokoro_endings.py [--limit N] [--out DIR] [--tempo 1.35] [--jobs 8]
"""
import argparse, os, re, subprocess, sys
from concurrent.futures import ThreadPoolExecutor

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "experiments", "kokoro_final_units")
ENTRY = re.compile(r'^\["(\d+00f[bc]?)"\]=\{([\d.]+),("[^"]*"),("[^"]*")\},\s*$')

HEADER = ("-- Generated by tools/build_kokoro_endings.py. Phrase-final ending clips of the Kokoro voice: <key>00f, 00fb, 00fc (key = phoneme indices of\n"
          "-- two digits each, 00 = end of the word). Unit = { seconds, head spectrum, tail spectrum }. The file is units/<name>.ogg. Cut from words said\n"
          "-- alone (falling pitch), then sped up with the pitch kept (%s), to the length of the same ending cut mid-phrase.\n"
          "TTS_KokoroEndingClips = {\n")


def twin_lengths():
    """Mean length of the mid-phrase clips of each unit key (TTS_KokoroHQ), to speed an ending up to its twin."""
    tw = {}
    for line in open(os.path.join(ROOT, "TTS_KokoroHQ", "Units.lua"), encoding="utf-8"):
        m = re.match(r'\["(\d+00)[bcd]?"\]=\{([\d.]+)', line)
        if m: tw.setdefault(m.group(1), []).append(float(m.group(2)))
    return {k: sum(v) / len(v) for k, v in tw.items()}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--limit", type=int, default=0)
    ap.add_argument("--out", default=os.path.join(ROOT, "TTS_KokoroHQ_Endings"))
    ap.add_argument("--tempo", type=float, default=1.35)
    ap.add_argument("--only", default="", help="comma separated clip names (a trial)")
    ap.add_argument("--uniform", action="store_true", help="the same tempo for every clip (default: each clip to the length of its mid-phrase twin)")
    ap.add_argument("--min", type=float, default=1.0)
    ap.add_argument("--max", type=float, default=1.8)
    ap.add_argument("--jobs", type=int, default=8)
    a = ap.parse_args()
    entries = []
    for line in open(os.path.join(SRC, "Units.lua.bak"), encoding="utf-8"):
        m = ENTRY.match(line)
        if m: entries.append((m.group(1), m.group(3), m.group(4), float(m.group(2))))
    if a.only: entries = [e for e in entries if e[0] in a.only.split(",")]
    if a.limit: entries = entries[::max(1, len(entries) // a.limit)][:a.limit]
    twin = {} if a.uniform else twin_lengths()
    def tempo_of(e):   # old length / twin length, within [min, max]; no twin: --tempo
        t = twin.get(re.match(r"(\d+00)", e[0]).group(1))
        return a.tempo if not t else min(a.max, max(a.min, e[3] / t))
    udir = os.path.join(a.out, "units")
    os.makedirs(udir, exist_ok=True)

    def one(e):
        src, dst = os.path.join(SRC, "units", e[0] + ".ogg"), os.path.join(udir, e[0] + ".ogg")
        subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", src, "-filter:a", "atempo=%g" % tempo_of(e),
                        "-ar", "16000", "-ac", "1", "-c:a", "libvorbis", "-q:a", "5", dst], check=True)
        return e, e[3], e[3] / tempo_of(e)   # lengths as the engine counts them: the cut length, not the padded file

    with ThreadPoolExecutor(a.jobs) as ex: res = list(ex.map(one, entries))
    with open(os.path.join(a.out, "Units.lua"), "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER % ("each clip to the length of its mid-phrase twin, %g to %g times, else %gx" % (a.min, a.max, a.tempo) if not a.uniform else "%gx" % a.tempo))
        for e, old, new in sorted(res, key=lambda r: r[0][0]):
            f.write('["%s"]={%.3f,%s,%s},\n' % (e[0], new, e[1], e[2]))
        f.write('}\nTTS_Diphone.AddUnits("kokoro", TTS_KokoroEndingClips, "Interface\\\\AddOns\\\\TTS_KokoroHQ_Endings\\\\")\n')
    o, n = sum(r[1] for r in res), sum(r[2] for r in res)
    print("%d clips, mean %.3f s -> %.3f s (x%.3f)" % (len(res), o / len(res), n / len(res), o / n))


if __name__ == "__main__":
    sys.exit(main())
