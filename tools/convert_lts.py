"""Converts Festival's CMU letter-to-sound decision trees (cmu_lts_rules.scm) into a compact Lua file (LTS.lua).

Usage: python -I convert_lts.py <cmu_lts_rules.scm> <out LTS.lua> <phone_order_file>
phone_order_file: one ARPAbet name per line in index order (AA, AE, AH0, AH, ...), used to turn leaf phones
into the addon's one-character phoneme codes (chr(48 + index)). Primary stress is written as a "^" before the
vowel and secondary stress as "~" (same convention as Words.lua).

Tree layout in the output, per letter: parallel arrays F, V, N in depth-first order.
  Node i with F[i] ~= 0: look at the letter at offset F[i] from the current one (negative = before);
    if it equals V[i] continue at i + 1, otherwise at N[i].
  Leaf i has F[i] == 0 and V[i] = the phone string ("" = no sound).
"""
import re
import sys

src, out, order_file = sys.argv[1:4]
order = [l.strip() for l in open(order_file) if l.strip()]
index = {p: i + 1 for i, p in enumerate(order)}   # 0 = silence

text = open(src, encoding="latin-1").read()
text = re.sub(r";[^\n]*", "", text)                 # strip comments
start = text.index("(set! cmu_lts_rules '(") + len("(set! cmu_lts_rules '")
tokens = re.findall(r"\(|\)|[^\s()]+", text[start:])

pos = 0


def parse():
    global pos
    t = tokens[pos]
    pos += 1
    if t != "(":
        return t
    items = []
    while tokens[pos] != ")":
        items.append(parse())
    pos += 1
    return items


top = parse()                                       # list of (letter tree)


def feat_offset(name):
    # p.name -> -1, p.p.name -> -2, n.name -> 1, n.n.n.name -> 3 ...
    parts = name.split(".")
    sign = -1 if parts[0] == "p" else 1
    return sign * (len(parts) - 1)


def phone_code(p):
    base = re.sub(r"\d", "", p).upper()
    digit = p[-1] if p[-1].isdigit() else ""
    if base == "AX":
        base = "AH0"
    if base == "AH" and digit == "0":
        base = "AH0"
    if base not in index:
        return ""
    mark = ""
    if base != "AH0":
        mark = {"1": "^", "2": "~"}.get(digit, "")
    return mark + chr(48 + index[base])


def leaf_value(leaf):
    # leaf = [[(phone prob) ..., best]] ; best may be "_epsilon_" or "k-s"
    best = leaf[0][-1]
    if isinstance(best, list):
        best = best[0]
    if best == "_epsilon_":
        return ""
    return "".join(phone_code(p) for p in best.split("-"))


def is_node(t):
    return (isinstance(t, list) and len(t) == 3 and isinstance(t[0], list) and len(t[0]) == 3
            and isinstance(t[0][0], str) and t[0][0].endswith(".name") and t[0][1] == "is")


def flatten(tree):
    F, V, N = [], [], []

    def walk(t):
        i = len(F)
        if is_node(t):
            F.append(feat_offset(t[0][0]))
            V.append(t[0][2])
            N.append(0)
            walk(t[1])
            N[i] = len(F) + 1                       # 1-based index of the "no" subtree
            walk(t[2])
        else:
            F.append(0)
            V.append(leaf_value(t))
            N.append(0)

    walk(tree)
    return F, V, N


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


parts = ["-- Generated by tools/convert_lts.py from Festival's cmu_lts_rules.scm (CSTR, University of Edinburgh; see CREDITS.txt).\n",
         "-- Letter-to-sound decision trees. See the converter for the layout.\n", "TTS_DiphoneLTS = {\n"]
total = 0
for entry in top:
    letter, tree = entry[0], entry[1]
    F, V, N = flatten(tree)
    total += len(F)
    parts.append('%s = { F = {%s}, V = {%s}, N = {%s} },\n' % (
        letter, ",".join(map(str, F)), ",".join(lua_str(v) for v in V), ",".join(map(str, N))))
parts.append("}\n")
open(out, "w", encoding="ascii").write("".join(parts))
print("letters:", len(top), "nodes:", total)
