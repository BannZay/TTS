# Packages the generated kal clips (all lengths: 1 short, 2 normal, 3 long) into the TTS_Kal voice addon.
# Sources (any that exist): TTS\diphones + TTS\Diphones.lua (fresh generate_festival output) and what TTS_Kal
# already has. Run after generate_festival.ps1.
$ErrorActionPreference='Stop'
$root = Split-Path $PSScriptRoot -Parent
$kal  = Join-Path $root 'TTS_Kal'
New-Item -ItemType Directory -Force "$kal\diphones" | Out-Null

$dur=[ordered]@{}
function ReadDur($file){ if(Test-Path $file){ foreach($l in Get-Content $file){ if($l -match '^\["(\d{5})"\]=([\d.]+)'){ $script:dur[$matches[1]] = $matches[2] } } } }
ReadDur "$kal\Diphones.lua"; ReadDur "$root\TTS\Diphones.lua"

# collect the clip files from every place they may be (fresh output first)
$dirs = "$root\TTS\diphones","$kal\diphones" | ? { Test-Path $_ }
$lines=@(); $moved=0
foreach($k in ($dur.PSBase.Keys | Sort-Object)){
  $target = Join-Path "$kal\diphones" "$k.ogg"
  $src = $dirs | % { Join-Path $_ "$k.ogg" } | ? { Test-Path $_ } | select -First 1
  if(-not $src){ throw "missing clip $k.ogg" }
  if((Resolve-Path $src).Path -ne $target){ Move-Item $src $target -Force; $moved++ }
  $lines += '["{0}"]={1}' -f $k,$dur[$k] }

Set-Content "$kal\Diphones.lua" ("-- Generated by tools/build_kal.ps1. Kal voice: diphone key = two 2-digit phoneme indices + length variant (1 short, 2 normal, 3 long) -> seconds`nTTS_KalClips = {`n" + ($lines -join ",`n") + "`n}`nTTS_Diphone.RegisterVoice(`"kal`", { name = `"Kal`", gender = `"male`", quality = `"robotic`", speedClips = true, clips = TTS_KalClips, base = `"Interface\AddOns\TTS_Kal\`" })`n") -Encoding ascii

